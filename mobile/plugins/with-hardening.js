/**
 * Release hardening config plugin (Continuous Native Generation: never edit android/ or ios/).
 *
 * - Android: a network security config with no cleartext and system CAs only in release builds
 *   (debug builds stay permissive so Metro and debugging proxies work).
 * - Optional certificate pinning: list your API hosts and CA-level SPKI SHA-256 pins in
 *   plugins/pins.json. With an empty list (the default) nothing is pinned.
 *     Android -> <pin-set> with an expiration date (fails open after it).
 *     iOS     -> NSAppTransportSecurity / NSPinnedDomains (no expiry: keep the list current).
 * - Optional App Attest entitlement: pass { appAttestEnvironment: "production" | "development" }
 *   when you wire an app-integrity provider (see src/lib/security/integrity.ts).
 *
 * Pin the CA (root / intermediate), never the leaf: leaf keys rotate on every renewal.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withEntitlementsPlist, withInfoPlist } = require('expo/config-plugins');

const PINS = require('./pins.json');
const CONFIG_NAME = 'network_security_config';

function hasPins() {
  return Array.isArray(PINS.domains) && PINS.domains.length > 0 && Array.isArray(PINS.pins) && PINS.pins.length > 0;
}

function releaseXml() {
  const pinned = hasPins()
    ? `
    <domain-config cleartextTrafficPermitted="false">
${PINS.domains.map((domain) => `        <domain includeSubdomains="false">${domain}</domain>`).join('\n')}
        <pin-set expiration="${PINS.expiration}">
${PINS.pins.map((pin) => `            <!-- ${pin.name} -->\n            <pin digest="SHA-256">${pin.spki}</pin>`).join('\n')}
        </pin-set>
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </domain-config>`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-hardening.js from plugins/pins.json. Do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>${pinned}
</network-security-config>
`;
}

function debugXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Debug builds only (generated by plugins/with-hardening.js): Metro needs cleartext and user
     CAs allow a debugging proxy. Release builds use src/main/res/xml/${CONFIG_NAME}.xml. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;
}

function write(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

function withAndroidNetworkSecurity(config) {
  config = withDangerousMod(config, [
    'android',
    async (mod) => {
      const src = path.join(mod.modRequest.platformProjectRoot, 'app', 'src');
      write(path.join(src, 'main', 'res', 'xml', `${CONFIG_NAME}.xml`), releaseXml());
      for (const variant of ['debug', 'debugOptimized']) {
        write(path.join(src, variant, 'res', 'xml', `${CONFIG_NAME}.xml`), debugXml());
      }
      return mod;
    },
  ]);
  return withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application) application.$['android:networkSecurityConfig'] = `@xml/${CONFIG_NAME}`;
    return mod;
  });
}

function withIosPinning(config) {
  if (!hasPins()) return config;
  return withInfoPlist(config, (mod) => {
    const ats = { ...(mod.modResults.NSAppTransportSecurity ?? {}) };
    ats.NSAllowsArbitraryLoads = false;
    const pinned = { ...(ats.NSPinnedDomains ?? {}) };
    for (const domain of PINS.domains) {
      pinned[domain] = {
        NSIncludesSubdomains: false,
        NSPinnedCAIdentities: PINS.pins.map((pin) => ({ 'SPKI-SHA256-BASE64': pin.spki })),
      };
    }
    ats.NSPinnedDomains = pinned;
    mod.modResults.NSAppTransportSecurity = ats;
    return mod;
  });
}

function withAppAttest(config, environment) {
  if (environment !== 'production' && environment !== 'development') return config;
  return withEntitlementsPlist(config, (mod) => {
    mod.modResults['com.apple.developer.devicecheck.appattest-environment'] = environment;
    return mod;
  });
}

module.exports = function withHardening(config, props = {}) {
  config = withAndroidNetworkSecurity(config);
  config = withIosPinning(config);
  return withAppAttest(config, props.appAttestEnvironment);
};

module.exports.releaseXml = releaseXml;
module.exports.debugXml = debugXml;
