class CrudGenerator(BaseGenerator):
    """Create a small CRUD scaffold inside an existing plugin."""

    def create(self, name: str, plugin: str, force: bool = False) -> ScaffoldResult:
        plugin_slug = Naming.slug(plugin)
        plugin_dir = self.root / "plugins" / plugin_slug
        if not plugin_dir.exists():
            raise ValueError(f"Plugin '{plugin_slug}' does not exist. Create it first with plugin:create.")

        resource = Naming.studly(name)
        resource_slug = Naming.slug(name)
        files: list[str] = []

        self.write(plugin_dir / "models" / f"{resource_slug}.py", self.model_template(resource), files, force)
        self.write(plugin_dir / "schemas" / f"{resource_slug}.py", self.schema_template(resource), files, force)
        self.write(plugin_dir / "services" / f"{resource_slug}_service.py", self.service_template(resource), files, force)
        self.write(plugin_dir / "admin" / f"{resource_slug}_table.py", self.table_template(resource), files, force)
        self.write(
            plugin_dir / "database" / "migrations" / f"0001_create_{resource_slug}.py",
            self.migration_template(resource, resource_slug),
            files,
            force,
        )

        return ScaffoldResult(
            message=f"CRUD resource '{resource}' created in plugin '{plugin_slug}'.",
            files=files,
        )

